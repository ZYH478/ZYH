#!/usr/bin/env python
"""iter063：对 iter37 PKI 候选 msdgs_pki_l4 补跑 seed 1/2/3，独立重载评测每个 best.pt。

背景与 owner 决策：
- iter37 PKI（MSDGS135eq 基座 + backbone 层4 C3k2->PKIC3k2 并联 DW 3/5/7）seed0 单点
  test mAP50=0.73878（+0.5pp vs gsdown 0.7338，+0.6pp vs MSDGS 0.732411），但当时因
  test mAP50-95 掉（0.38788 < 0.4018）被双指标标准判死、未上多 seed。
- owner 现放宽判定为「只要 mAP50 多 seed 均值稳健提升即可」（mAP50-95/crazing 仍完整记录，
  不作否决项）。本轮补跑 seed 1/2/3，与现存 seed0 合并成四 seed，看 mAP50 均值是否稳健
  > MSDGS 锚点 0.7324（最好 > gsdown 0.7379）。

铁律（同 DCNv2 多 seed 口径）：
- 结构、训练协议与 iter37 seed0 完全一致，只改 seed 和 run name。
- 每个 seed 训完由独立新进程（eval_msdgs_candidate.py）重载磁盘 best.pt 做 val/test 真值。
- seed0 复用 iter37 现存 runs_pki_gsdown_e250/report.json 的权威结果，不重训。
- DCNv2 seed0 涨 mAP50、多 seed 塌回的教训：单 seed 涨不算数，只认多 seed 均值。

远程用法：
    source /root/miniconda3/etc/profile.d/conda.sh && conda activate yolo26
    cd /root/autodl-tmp/neu-det-yolo26
    python install_gsconv_modules.py    # GSConv/VoVGSCSP（gsdown head 必需）
    python install_msdgs_module.py      # MSDGS（基座 neck）
    python install_pki_module.py        # PKIC3k2（本候选）
    setsid python -u train_multiseed_pki.py > pki_multiseed_e250.log 2>&1 &

输出：
- runs_pki_multiseed_e250/msdgs_pki_l4_seed{1,2,3}/weights/best.pt
- runs_pki_multiseed_e250/independent_seed{1,2,3}_report.json
- runs_pki_multiseed_e250/report.json / report.md / status.json
"""
